"""Table 2 of the paper: the best single ring on noisy Mackey-Glass under real lasers, from the result files.

Rows: white-noise (Lorentzian) linewidth of the pump laser; columns: per-symbol detuning jitter, test NMSE at
the fixed operating point (mask_drop trial 211, Q 1.9e6), test NMSE after re-choosing the operating point under
that laser, and the Q of the re-chosen point. Writes paper/tables/table2.tex.

    python experiments/make_table2.py
"""
import csv
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
EN = "--lang" in sys.argv and sys.argv[sys.argv.index("--lang") + 1] == "en"
OUT = os.path.join(ROOT, "paper_en" if EN else "paper", "tables", "table2.tex")
CAPTION_EN = (r"\caption{The best single ring under real lasers (stronger drop coupling, Mackey--Glass, all other realistic noise "
              r"unchanged). The detuning jitter is the laser's white frequency noise averaged over each symbol. ``Fixed point'' is the "
              r"point chosen under the 1\% jitter assumption ($Q=1.9\times10^{6}$); ``re-selected'' repeats the selection of "
              r"Section~\ref{sec:protocol} under this laser's noise (56 candidates per series binned by $Q$). Three series $\times$ "
              r"six new pairs. The two columns use different noise realisations; the same point differs by about 9\% between them.}")
HEADER_EN = r"intrinsic linewidth & jitter/symbol & fixed point & re-selected & re-selected $Q$ \\"
FLICKER_EN = [r"100~kHz, flicker noise (1~MHz corner) and 1~MHz lock", r"1.6~kHz, flicker noise (10~MHz corner), no lock"]


def sci(x):
    e = math.floor(math.log10(x))
    m = x / 10 ** e
    if round(m, 1) >= 10:
        m, e = m / 10, e + 1
    return rf"${m:.1f}\times10^{{{e}}}$"


def main():
    fixed = {r["condition"]: r for r in csv.DictReader(open(os.path.join(RES, "laser_noise_summary.csv")))}
    resel = {float(r["linewidth_hz"]): r for r in csv.DictReader(open(os.path.join(RES, "laser_reselect_summary.csv")))}
    rows = [("100~Hz", "lw100"), ("1.6~kHz", "lw1600"), ("16~kHz", "lw16k"), ("100~kHz", "lw100k"), ("1~MHz", "lw1M")]
    lines = [r"\begin{table}[htbp]", r"\centering",
             r"\caption{真实激光下最好的单环（加大下载端口耦合组，Mackey--Glass，现实噪声的其余各项不变）。"
             r"失谐抖动由激光的白频率噪声按每个符号平均得到；“固定工作点”是 1\% 抖动假设下选出的点（$Q=1.9\times10^{6}$），"
             r"“重选”是在该激光的噪声下按第~\ref{sec:protocol}~节的流程重新选点（每条序列 56 个按 $Q$ 分档的候选）。"
             r"3 条序列 $\times$ 6 对新运行。两列用了不同的噪声实现，同一个工作点在两列之间约有 9\% 的差别。}",
             r"\label{tab:laser}", r"\small", r"\begin{tabular}{p{4.2cm}cccc}", r"\toprule",
             r"激光本征线宽 & 每符号抖动 & 固定工作点 & 重选后 & 重选点的 $Q$ \\", r"\midrule"]
    for label, key in rows:
        f = fixed[key]
        lw = float(f["linewidth_hz"])
        r = resel.get(lw)
        if r:
            qs = sorted({float(q) for q in __import__("re").findall(r"\(Q ([0-9.e+]+)\)", r["chosen"])})
            q_text = (", " if EN else "、").join(sci(q) for q in qs)            # each number in its own math group
            re_text = sci(float(r["reselected_test"]))
        else:
            q_text, re_text = "--", "--"
        lines.append(f"{label} & {100 * float(f['jitter_rms']):.2g}\\% & {sci(float(f['test_nmse']))} & {re_text} & {q_text} \\\\")
    fl = fixed["lw100k_flicker"]
    fl2 = fixed["lw1600_flicker10M"]
    lines += [r"\midrule",
              rf"100~kHz，加闪烁噪声（转折 1~MHz）和 1~MHz 锁定 & {100 * float(fl['jitter_rms']):.2g}\% & {sci(float(fl['test_nmse']))} & -- & -- \\",
              rf"1.6~kHz，加闪烁噪声（转折 10~MHz），不锁定 & {100 * float(fl2['jitter_rms']):.2g}\% & {sci(float(fl2['test_nmse']))} & -- & -- \\",
              r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    if EN:
        lines[2] = CAPTION_EN
        lines[7] = HEADER_EN
        k = lines.index(r"\midrule", 9)
        for j in (1, 2):
            lines[k + j] = FLICKER_EN[j - 1] + lines[k + j][lines[k + j].index(" & "):]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("% generated by experiments/make_table2.py; do not edit by hand\n" + "\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
