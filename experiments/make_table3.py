"""Table 3 of the paper: readout-side quantization of the best single ring against an ESN with a quantized input.

Reads results/readout_quantization.csv (experiments/readout_quantization.py) and writes paper/tables/table3.tex.

    python experiments/make_table3.py
"""
import csv
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "results", "readout_quantization.csv")
EN = "--lang" in sys.argv and sys.argv[sys.argv.index("--lang") + 1] == "en"
OUT = os.path.join(ROOT, "paper_en" if EN else "paper", "tables", "table3.tex")
BITS = ["4", "5", "6", "7", "8", "9", "10", "12"]


def sci(x):
    e = math.floor(math.log10(x))
    m = x / 10 ** e
    if round(m, 1) >= 10:
        m, e = m / 10, e + 1
    return rf"${m:.1f}\times10^{{{e}}}$"


def main():
    rows = list(csv.DictReader(open(SRC)))
    val = {(r["system"], r["adc"], r["bits"]): float(r["test_nmse"]) for r in rows}
    ring0, esn0 = val[("ring", "none", "")], val[("ESN 31", "none", "")]
    lines = [r"\begin{table}[htbp]", r"\centering",
             r"\caption{读出端量化。最好的单环（加大下载端口耦合组，现实噪声，Mackey--Glass）的 31 路读数各接一个 $N$ 位模数转换器，"
             r"满量程在拟合用的那次运行上按每路读数的范围标定一次，测试运行沿用；“线性”直接量化光电流，“对数”在转换器前加对数放大器。"
             r"对照是输入经 $N$ 位量化、不加其他噪声的 31 节点 ESN（一个随机储备池）。3 条序列 $\times$ 6 对新运行的几何平均。"
             rf"不量化时微环为 {sci(ring0)}，无噪声的 ESN 为 {sci(esn0)}。}}",
             r"\label{tab:quant}", r"\small", r"\begin{tabular}{cccc}", r"\toprule",
             r"位数 $N$ & 微环，线性转换器 & 微环，对数放大器 & ESN 31，输入量化 \\", r"\midrule"]
    for b in BITS:
        lines.append(f"{b} & {sci(val[('ring', 'linear', b)])} & {sci(val[('ring', 'log', b)])} & "
                     f"{sci(val[('ESN 31', 'input', b)])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    if EN:
        lines[2] = (r"\caption{Readout quantization. Each of the 31 readings of the best single ring (stronger drop coupling, "
                    r"realistic noise, Mackey--Glass) has its own $N$-bit converter, with the full scale of each channel calibrated "
                    r"once on the fitting run and kept for the test run; ``linear'' digitises the photocurrent, ``log'' places a "
                    r"logarithmic amplifier before the converter. Reference: a 31-node ESN (one random reservoir) whose input is "
                    r"quantized to $N$ bits, with no other noise. Geometric mean over three series $\times$ six new pairs. "
                    rf"Unquantized, the resonator reaches {sci(ring0)} and the noise-free ESN {sci(esn0)}.}}")
        lines[7] = r"bits $N$ & resonator, linear & resonator, log amplifier & ESN 31, quantized input \\"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("% generated by experiments/make_table3.py; do not edit by hand\n" + "\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
